/**
  * @brief Keep PA2 available for ADC1_IN3.
  * @note  STM32G431 erratum ES0431 2.2.6 documents that a corrupted backup
  *        domain can unexpectedly enable LSCO on PA2 after an abnormal power
  *        cycle. This project does not use RTC/LSE backup-domain state, so a
  *        backup-domain reset is safe and removes that hidden PA2 owner.
  */
static void PA2_LSCO_Guard_Init(void)
{
  __HAL_RCC_PWR_CLK_ENABLE();
  HAL_PWR_EnableBkUpAccess();

  __HAL_RCC_BACKUPRESET_FORCE();
  __DSB();
  __HAL_RCC_BACKUPRESET_RELEASE();

  CLEAR_BIT(RCC->BDCR, RCC_BDCR_LSCOEN | RCC_BDCR_LSCOSEL);
}

