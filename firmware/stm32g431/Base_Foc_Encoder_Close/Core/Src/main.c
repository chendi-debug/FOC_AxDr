/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */
  PA2_LSCO_Guard_Init();

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_USB_Device_Init();
  MX_TIM1_Init();
  MX_ADC1_Init(); /* TIM1_CH4 hardware-triggered injected current sampling */
  MX_SPI1_Init();

  /* USER CODE BEGIN 2 */

	Motor_StateMachine_Init(&MotorSystem);
	/* Keep the power stage off while the 1024-sample zero-current calibration runs. */
	__HAL_TIM_MOE_DISABLE(&htim1);
	if (CurrentSense_Start() != HAL_OK)
	{
		Error_Handler();
	}

	
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
	static uint32_t last_encoder_tick = 0;
	static uint8_t pwm_outputs_enabled = 0U;
	uint32_t current_tick = HAL_GetTick(); /* 当前HAL时基，单位：ms */

	/* Start the original alignment/PWM sequence only after current offsets are valid. */
	if ((pwm_outputs_enabled == 0U) && (CurrentSense_Calibrated != 0U))
	{
		MotorSystem.Alignment.Start_Tick_ms = current_tick;
		__HAL_TIM_MOE_ENABLE(&htim1);
		pwm_outputs_enabled = 1U;
	}

	/* 编码器读取放在主循环，避免阻塞TIM1控制中断。 */
	if ((current_tick - last_encoder_tick) >= ENCODER_TASK_PERIOD_MS)
	{
		last_encoder_tick = current_tick;
		Motor_EncoderTask_1kHz(&MotorSystem);
	}

	Vofa_Send_Task();
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

